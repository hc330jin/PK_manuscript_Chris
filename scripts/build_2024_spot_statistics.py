"""Generate the manuscript's 2024 return table from date,price daily CSV data."""

import argparse
import csv
import hashlib
import json
import math
from datetime import date, timedelta
from pathlib import Path
from statistics import fmean, median, stdev


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("prices", type=Path)
    args = parser.parse_args()
    with args.prices.open(encoding="utf-8-sig", newline="") as stream:
        rows = list(csv.DictReader(stream))
    prices = {date.fromisoformat(row["date"]): float(row["price"]) for row in rows}
    if len(prices) != len(rows):
        raise ValueError("Duplicate price dates")
    dates = [date(2024, 1, 1) + timedelta(days=i) for i in range(366)]
    required = [date(2023, 12, 31), *dates]
    if any(d not in prices or not math.isfinite(prices[d]) or prices[d] <= 0
           for d in required):
        raise ValueError("Need positive daily prices from 2023-12-31 to 2024-12-31")
    returns = [math.log(prices[d]) - math.log(prices[d - timedelta(days=1)])
               for d in dates]
    mean = fmean(returns)
    centered = [r - mean for r in returns]
    m2 = fmean(x ** 2 for x in centered)
    skew = fmean(x ** 3 for x in centered) / m2 ** 1.5
    kurt = fmean(x ** 4 for x in centered) / m2 ** 2
    jb = len(returns) / 6 * (skew ** 2 + (kurt - 3) ** 2 / 4)
    stats = {"Observations": len(returns), "Mean": mean,
             "Standard deviation": stdev(returns), "Skewness": skew,
             "Kurtosis": kurt, "Minimum": min(returns), "Median": median(returns),
             "Maximum": max(returns), "JB": jb}
    digest = hashlib.sha256(args.prices.read_bytes()).hexdigest()
    lines = ["% Generated by scripts/build_2024_spot_statistics.py; do not edit.",
             f"% Source CSV SHA-256: {digest}",
             r"\begin{table}[htbp]", r"\centering", r"\begin{tabular}{lr}",
             r"\toprule", r"Statistic & Value \\", r"\midrule"]
    for key, value in stats.items():
        formatted = str(value) if key == "Observations" else f"{value:.6f}"
        lines.append(f"{key} & ${formatted}$ " + r"\\")
    lines.extend([r"\bottomrule", r"\end{tabular}",
                  r"\caption{\textbf{Descriptive statistics of daily Bitcoin log returns, 2024.} "
                  r"Returns are $\log S_d-\log S_{d-1}$ for all 366 calendar dates in 2024; "
                  r"the first return uses the December 31, 2023 close. Standard deviation "
                  r"uses the sample denominator. Skewness and Pearson kurtosis use "
                  r"empirical central moments; JB is the Jarque--Bera statistic.}",
                  r"\label{tab:btc_log_return_descriptive_statistics}", r"\end{table}"])
    output = Path(__file__).resolve().parents[1] / "Sections/02_data_tables/btc_returns_2024.tex"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n")
    print(json.dumps({"source_sha256": digest, **stats,
                      "JB_asymptotic_p": math.exp(-jb / 2),
                      "annualized_volatility_365": stdev(returns) * math.sqrt(365)}, indent=2))


if __name__ == "__main__":
    main()
